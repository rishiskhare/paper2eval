#!/usr/bin/env python3
"""Grade every rung/<task>/* branch and the reference (twice) with the task's verifier.

Writes tasks/<task>/review/rungs/<rung>.patch (diff vs <task>-stripped) and tasks/<task>/review/sanity.md.
Usage: scripts/run_sanity.py <task> <expected.json>
"""
import json
import subprocess
import sys
import tarfile
import io
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
task, expected = sys.argv[1], json.loads(Path(sys.argv[2]).read_text())
T = ROOT / "tasks" / task


def git(*a, **kw):
    return subprocess.run(["git", "-C", str(ROOT), *a], check=True, capture_output=True, **kw).stdout


def export(ref, dest):
    data = git("archive", "--format=tar", ref, f"tasks/{task}/repo")
    with tarfile.open(fileobj=io.BytesIO(data)) as t:
        t.extractall(dest, filter="data")
    return Path(dest) / "tasks" / task / "repo"


tmp = Path(tempfile.mkdtemp(prefix=f"sanity-{task}-"))
pristine = export(f"{task}-stripped", tmp / "pristine")
rungs = sorted(b.decode().strip() for b in git("for-each-ref", "--format=%(refname:short)", f"refs/heads/rung/{task}/").split())
runs = [(r.split("/")[-1], r) for r in rungs] + [("reference#1", f"{task}-reference"), ("reference#2", f"{task}-reference")]
(T / "review" / "rungs").mkdir(parents=True, exist_ok=True)
rows, ok, ref_results = [], True, []
for name, ref in runs:
    if not name.startswith("reference"):
        (T / "review" / "rungs" / f"{name}.patch").write_bytes(git("diff", f"{task}-stripped", ref, "--", f"tasks/{task}/repo"))
    sub = export(ref, tmp / name)
    out = tmp / f"out-{name}"
    data_args = (["--corpora", str(T / "evaluator" / "heldout")] if task == "fsst"
                 else ["--spec", str(T / "tests" / "heldout_spec.json")])
    subprocess.run([sys.executable, str(T / "evaluator" / "eval.py"), "--submission", str(sub), "--pristine", str(pristine),
                    "--harness", str(T / "harness" / "harness.cpp"), *data_args,
                    "--reference", str(T / "tests" / "reference_values.json"), "--workdir", str(tmp / f"work-{name}"),
                    "--out-dir", str(out), "--verifier-tag", "sanity"], check=True, capture_output=True)
    res = json.loads((out / "results.json").read_text())
    exp = expected[name.split("#")[0]]
    good = res["pass"] == exp["pass"] and res["gate_failed"] == exp["gate_failed"]
    ok &= good
    if name.startswith("reference"):
        if task == "fsst":
            ref_results.append({n: (m.get("output_bytes"), m.get("ratio")) for n, m in res["corpora"].items()})
        else:
            ref_results.append({n: m.get("eps") and {e: v["total_segments"] for e, v in m["eps"].items()}
                                for n, m in res["workloads"].items()})
    reason = (res["reason"] or "").replace("|", "\\|")
    rows.append(f"| {name} | `{ref}` | {res['reward']} | {res['pass']} | {res['gate_failed'] or '-'} "
                f"| {exp['gate_failed'] or '-'} | {'yes' if good else '**NO**'} | {reason[:300]} |")
identical = len(ref_results) == 2 and ref_results[0] == ref_results[1]
ok &= identical
md = [f"# {task} sanity rungs", "", "Generated by `scripts/run_sanity.py`. Held-out workloads, verifier from this commit.", "",
      "| run | ref | reward | pass | gate failed | expected gate | as expected | reason |",
      "|---|---|---|---|---|---|---|---|", *rows, "",
      f"Reference runs identical: **{'yes' if identical else 'NO'}**. All as expected: **{'yes' if ok else 'NO'}**.", ""]
(T / "review" / "sanity.md").write_text("\n".join(md))
print("\n".join(md))
sys.exit(0 if ok else 1)
